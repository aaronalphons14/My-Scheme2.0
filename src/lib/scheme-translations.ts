export function getLocalizedScheme(scheme: Scheme, language: LanguageCode): Scheme {
  if (language === "en") return scheme;
  const trans = schemeTranslationsMap[scheme.id]?.[language];
  const catLabel = categoryLabels[language]?.[scheme.category] || scheme.category;

  if (!trans) {
    return {
      ...scheme,
      category: catLabel as any,
    };
  }

  return {
    ...scheme,
    name: trans.name || scheme.name,
    department: trans.department || scheme.department,
    summary: trans.summary || scheme.summary,
    benefit: trans.benefit || scheme.benefit,
    category: catLabel as any,
  };
}

export function getLocalizedCategory(category: SchemeCategory, language: LanguageCode): string {
  return categoryLabels[language]?.[category] || category;
}

